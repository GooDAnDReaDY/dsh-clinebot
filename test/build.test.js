/**
 * Locks the reconstructed browser-half source tree to the artifact that ships.
 *
 * `lib/client.js` is generated; before this suite existed there was no way to tell
 * a stale bundle from a fresh one, and no way to edit the client at all except in
 * the artifact. These tests make the artifact reproducible: the build is a pure
 * function, and the committed bundle must equal its output byte for byte.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { MODULES, OUT, renderClientBundle } from '../scripts/build-client.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8')
const pkg = JSON.parse(read('package.json'))

/** Report the first differing line, so a stale artifact does not dump 166 kB. */
function firstDifference(committed, generated) {
  const a = committed.split('\n')
  const b = generated.split('\n')
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) {
      return `line ${i + 1}\n  committed: ${JSON.stringify(a[i])}\n  generated: ${JSON.stringify(b[i])}`
    }
  }
  return 'the two differ only in trailing newlines'
}

test('the committed bundle is exactly what the build produces', () => {
  const committed = read(OUT)
  const generated = renderClientBundle(root)
  assert.ok(
    committed === generated,
    `${OUT} is stale or was hand-edited — run \`npm run build:client\` and commit the result.\nFirst difference at ${firstDifference(committed, generated)}`,
  )
})

test('the build script runs standalone and leaves the committed bytes alone', () => {
  // Build to a scratch path: the CLI path is exercised without the test itself
  // rewriting the committed artifact.
  const scratch = path.join(os.tmpdir(), `dsh-clinebot-build-${process.pid}.js`)
  try {
    const stdout = execFileSync(
      process.execPath,
      [path.join(root, 'scripts/build-client.js'), '--out', scratch],
      { cwd: root, encoding: 'utf8' },
    )
    assert.match(stdout, new RegExp(`${MODULES.length} modules, \\d+ bytes`))
    assert.equal(fs.readFileSync(scratch, 'utf8'), read(OUT))
  } finally {
    fs.rmSync(scratch, { force: true })
  }
})

test('the emission order matches the markers in the bundle', () => {
  const markers = [...read(OUT).matchAll(/^\/\/ --- (src\/[^\n]+) ---$/gm)].map((m) => m[1])
  assert.deepEqual(markers, MODULES)
})

test('every module in the emission order exists on disk', () => {
  for (const rel of MODULES) {
    assert.ok(fs.existsSync(path.join(root, rel)), `missing client module: ${rel}`)
  }
})

test('entry.js stays last, so it can own the activation contract', () => {
  assert.equal(MODULES.at(-1), 'src/client/entry.js')
  assert.match(read('src/client/entry.js'), /module\.exports = \{ apply, inject: \[[^\]]*\] \}/)
})

test('the bundle declares the shell factory wrapper', () => {
  const bundle = read(OUT)
  assert.ok(bundle.startsWith('// @generated by scripts/build-client.js - DO NOT EDIT DIRECTLY.'))
  assert.ok(bundle.includes(`id: '${pkg.name}',`))
  assert.ok(bundle.includes('window.__ModuleLoader__.load({'))
  assert.ok(bundle.includes('factory: (require) => {'))
  assert.ok(bundle.endsWith('    return module.exports\n  },\n})\n'))
})

test('the published package never ships the sources or the tests', () => {
  assert.ok(pkg.files.includes('lib/'))
  for (const entry of pkg.files) {
    assert.ok(!/^(src|scripts|test)\//.test(entry), `files must not publish ${entry}`)
  }
})

test('every hardcoded version fallback tracks package.json', () => {
  // lib/proxy-token.js carries the version twice as a fallback for when the
  // manifest cannot be read, and the CHANGELOG heading names the release. Both
  // drift silently on a bump, so they are pinned to package.json here.
  const fallbacks = [...read('lib/proxy-token.js').matchAll(/'(0\.\d+\.\d+)'/g)].map((m) => m[1])
  assert.ok(fallbacks.length > 0, 'expected version fallbacks in lib/proxy-token.js')
  for (const version of fallbacks) {
    assert.equal(version, pkg.version, 'lib/proxy-token.js fallback is out of step with package.json')
  }

  const headings = [...read('CHANGELOG.md').matchAll(/^## \[(\d+\.\d+\.\d+)\]/gm)].map((m) => m[1])
  assert.equal(headings[0], pkg.version, 'the newest CHANGELOG heading must be the released version')
  assert.ok(!/^## \[Unreleased\]/m.test(read('CHANGELOG.md')), 'release the Unreleased section on a bump')
})

test('every source module parses on its own', () => {
  // The modules are concatenated into one factory scope and share their
  // declarations, so they are syntax-checked rather than imported.
  for (const rel of MODULES) {
    execFileSync(process.execPath, ['--check', path.join(root, rel)], { stdio: 'pipe' })
  }
})
