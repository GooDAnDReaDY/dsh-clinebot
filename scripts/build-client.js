#!/usr/bin/env node
/**
 * Assemble the browser half of @goodandready/dsh-clinebot.
 *
 * The client bundle is one CommonJS factory registered on the shell's
 * `window.__ModuleLoader__`; the shell calls it with a single `require` and uses
 * the returned `module.exports` as the plugin. It is assembled by plain
 * concatenation rather than by a bundler: every file under `src/client/` is
 * emitted, in the order below, into that one factory scope. The modules therefore
 * share their top-level declarations — and the shell's `require` — instead of
 * importing from each other, which is why each file is written as a script
 * fragment with no `import`/`export` of its own.
 *
 * `src/client/entry.js` must stay last: it defines `apply` and owns the
 * activation contract (`module.exports = { apply, inject: [...] }`).
 *
 * `renderClientBundle()` is the whole build and is pure, so `test/build.test.js`
 * can assert that the committed `lib/client.js` is exactly what this produces.
 *
 * Output: lib/client.js
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = fileURLToPath(import.meta.url)
const root = path.resolve(path.dirname(HERE), '..')

/**
 * Emission order, relative to the repository root. Concatenation order is
 * load-bearing: `const` bindings are initialized as each module is reached, so a
 * module may only *call* another module's `const` after its own line has run.
 * Keeping declarations in dependency order (constants → shared helpers →
 * components → entry) is what makes that safe.
 */
export const MODULES = [
  'src/client/constants.js',
  'src/client/locales.js',
  'src/client/primitives.js',
  'src/client/styles.js',
  'src/client/api.js',
  'src/client/error-boundary.js',
  'src/client/progress-bar.js',
  'src/client/components/update-banner.js',
  'src/client/components/key-section.js',
  'src/client/components/accounts-section.js',
  'src/client/components/quota-section.js',
  'src/client/components/custom-models.js',
  'src/client/components/visible-models.js',
  'src/client/components/models-section.js',
  'src/client/components/stats-section.js',
  'src/client/components/diag-section.js',
  'src/client/components/sidebar-quota.js',
  'src/client/components/dashboard-overlay.js',
  'src/client/components/models-provider-card.js',
  'src/client/components/composer-cost.js',
  'src/client/settings-page.js',
  'src/client/entry.js',
]

/** Path of the committed bundle, relative to the repository root. */
export const OUT = 'lib/client.js'

/** Every module is separated by one blank line; the wrapper frames the lot. */
export function renderClientBundle(repoRoot = root) {
  const pkg = JSON.parse(fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8'))

  const prologue = `// @generated by scripts/build-client.js - DO NOT EDIT DIRECTLY.
// Edit modular source files in src/client/ instead.

window.__ModuleLoader__.load({
  id: '${pkg.name}',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    let React = require('react')

`

  const epilogue = `    return module.exports
  },
})
`

  let out = prologue
  for (const rel of MODULES) {
    const file = path.join(repoRoot, rel)
    if (!fs.existsSync(file)) throw new Error(`missing client module: ${rel}`)
    const body = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
    out += `// --- ${rel} ---\n${body}\n`
  }
  return out + epilogue
}

function main() {
  // `--out <path>` writes somewhere other than the committed artifact, which is how
  // the suite exercises this CLI without rewriting lib/client.js as a side effect.
  const flag = process.argv.indexOf('--out')
  const target = flag === -1
    ? path.join(root, OUT)
    : path.resolve(process.cwd(), process.argv[flag + 1] || '')

  const out = renderClientBundle()
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, out)
  console.log(`${path.relative(root, target) || target}: ${MODULES.length} modules, ${out.length} bytes`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === HERE) main()
