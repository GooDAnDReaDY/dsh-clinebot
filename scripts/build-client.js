export function renderClientBundle(repoRoot = root) {
  const pkg = JSON.parse(readFileSync(path.join(repoRoot, 'package.json'), 'utf8'))
  const prologue = `// @generated by scripts/build-client.js - DO NOT EDIT DIRECTLY.
// Edit modular source files in src/client/ instead.

window.__ModuleLoader__.load({
  id: '${pkg.name}',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    let React = require('react')

`
  const epilogue = `    return module.exports
  },
})
`
  let out = prologue
  for (const rel of MODULES) {
    const file = path.join(repoRoot, rel)
    if (!existsSync(file)) throw new Error(`missing client module: ${rel}`)
    const body = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim()
    out += `// --- ${rel} ---\n${body}\n\n`
  }
  return out + epilogue
}

const isCheck = process.argv.includes('--check')
const outFlag = process.argv.indexOf('--out')
const outFile = outFlag === -1
  ? defaultOut
  : path.resolve(process.cwd(), process.argv[outFlag + 1] || '')

const bundle = renderClientBundle(root)

if (isCheck) {
  if (!existsSync(outFile)) {
    console.error('[build-client] ERROR: lib/client.js does not exist!')
    process.exit(1)
  }
  const current = readFileSync(outFile, 'utf8')
  if (current !== bundle) {
    console.error('[build-client] ERROR: Drift detected between src/client/ and lib/client.js! Run "npm run build:client" to sync.')
    process.exit(1)
  }
  console.log('[build-client] Check mode: lib/client.js is up to date.')
  process.exit(0)
}

mkdirSync(path.dirname(outFile), { recursive: true })
// Write atomically so a concurrently running test never observes a partially
// assembled bundle.
const tempOut = `${outFile}.${process.pid}.${Date.now()}.tmp`
writeFileSync(tempOut, bundle, 'utf8')
try {
  renameSync(tempOut, outFile)
} catch {
  writeFileSync(outFile, bundle, 'utf8')
  try { unlinkSync(tempOut) } catch {}
}
const stats = statSync(outFile)
console.log(`[build-client] Rebuilt lib/client.js: ${stats.size} bytes (< 256 KiB limit)`)
console.log(`${path.relative(root, outFile) || outFile}: ${MODULES.length} modules, ${bundle.length} bytes`)

if (stats.size > 262144) {
  console.error('[build-client] ERROR: lib/client.js exceeds official DSH Store limit (262144 bytes)!')
  process.exit(1)
}

try {
  execFileSync(process.execPath, ['--check', outFile], { stdio: 'inherit' })
  console.log('[build-client] Syntax check: OK')
} catch (err) {
  console.error('[build-client] Syntax error in assembled lib/client.js!')
  process.exit(1)
}

const localEslintJs = path.join(root, 'node_modules', 'eslint', 'bin', 'eslint.js')
const hasLocalEslint = existsSync(localEslintJs)
const eslintCmd = hasLocalEslint ? process.execPath : 'eslint'
const eslintArgs = [
  '--no-config-lookup',
  '--rule', 'no-undef: 2',
  '--global', 'window,document,console,fetch,setTimeout,clearTimeout,AbortController,URL',
  outFile
]
if (hasLocalEslint) eslintArgs.unshift(localEslintJs)

try {
  execFileSync(eslintCmd, eslintArgs, { stdio: 'inherit' })
  console.log('[build-client] no-undef check: OK')
} catch (err) {
  if (err.code === 'ENOENT') {
    console.error('[build-client] ERROR: eslint binary not found! Install devDependencies (npm install) before building.')
    process.exit(1)
  }
  console.error('[build-client] no-undef violations found in assembled lib/client.js!')
  process.exit(1)
}
